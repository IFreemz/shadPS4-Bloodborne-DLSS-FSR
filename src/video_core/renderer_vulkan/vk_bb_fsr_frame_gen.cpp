FfxApiResource Image(vk::Image image, vk::Format format, vk::Extent2D extent, uint32_t state) {
    FfxApiResource resource{};
    resource.resource = reinterpret_cast<void*>(static_cast<VkImage>(image));
    resource.description.type = FFX_API_RESOURCE_TYPE_TEXTURE2D;
    resource.description.format = ffxApiGetSurfaceFormatVK(static_cast<VkFormat>(format));
    resource.description.width = extent.width;
    resource.description.height = extent.height;
    resource.description.depth = 1;
    resource.description.mipCount = 1;
    resource.description.flags = FFX_API_RESOURCE_FLAGS_NONE;
    resource.description.usage = FFX_API_RESOURCE_USAGE_READ_ONLY;
    resource.state = state;
    return resource;
}

ffxReturnCode_t DispatchGeneration(ffxDispatchDescFrameGeneration* params, void* user) {
    // FFX's swapchain passes scRGB (RenoDX HDR) with a luminance range of 0..0, which leaves
    // the UI found by comparing with the HUD-less image out of the generated frames.
    if (params->backbufferTransferFunction == FFX_API_BACKBUFFER_TRANSFER_FUNCTION_SCRGB &&
        params->minMaxLuminance[1] <= 0.f) {
        params->minMaxLuminance[0] = 0.f;
        params->minMaxLuminance[1] = 1000.f;
    }
    return api.dispatch(static_cast<ffxContext*>(user), &params->header);
}

void DestroyContext() {
    if (!context)
        return;
    // The swapchain may still present frames generated by it.
    (void)device.waitIdle();
    api.destroy(&context, nullptr);
    context = {};
    configured_on = false;
}

bool EnsureContext(vk::Extent2D display, vk::Extent2D render, bool inverted) {
    if (context && context_display == display && context_format == current_format &&
        context_inverted == inverted && render.width <= context_render.width &&
        render.height <= context_render.height)
        return true;
    DestroyContext();
    ffxCreateBackendVKDesc backend{};
    backend.header.type = FFX_API_CREATE_CONTEXT_DESC_TYPE_BACKEND_VK;
    backend.vkDevice = device;
    backend.vkPhysicalDevice = physical_device;
    backend.vkDeviceProcAddr =
        reinterpret_cast<PFN_vkGetDeviceProcAddr>(FsrUpscaler::FfxDeviceProcAddr());
    ffxCreateContextDescFrameGenerationHudless hudless{};
    hudless.header.type = FFX_API_CREATE_CONTEXT_DESC_TYPE_FRAMEGENERATION_HUDLESS;
    hudless.hudlessBackBufferFormat = ffxApiGetSurfaceFormatVK(current_format);
    backend.header.pNext = &hudless.header;
    ffxCreateContextDescFrameGeneration create{};
    create.header.type = FFX_API_CREATE_CONTEXT_DESC_TYPE_FRAMEGENERATION;
    create.header.pNext = &backend.header;
    create.flags = inverted ? FFX_FRAMEGENERATION_ENABLE_DEPTH_INVERTED : 0u;
    // An scRGB swapchain (RenoDX HDR) holds values above 1.
    if (current_format == VK_FORMAT_R16G16B16A16_SFLOAT)
        create.flags |= FFX_FRAMEGENERATION_ENABLE_HIGH_DYNAMIC_RANGE;
    create.displaySize = {display.width, display.height};
    // Room for the render size growing with a resolution patch change.
    const vk::Extent2D max_render{std::max(render.width, display.width),
                                  std::max(render.height, display.height)};
    create.maxRenderSize = {max_render.width, max_render.height};
    create.backBufferFormat = ffxApiGetSurfaceFormatVK(current_format);
    const auto result = api.create(&context, &create.header, nullptr);
    if (result != FFX_API_RETURN_OK) {
        context = {};
        LOG_ERROR(Render_Vulkan, "[FSR-FG] Context creation failed ({})", result);
        return false;
    }
    context_display = display;
    context_render = max_render;
    context_format = current_format;
    context_inverted = inverted;
    LOG_INFO(Render_Vulkan, "[FSR-FG] Context {}x{} (render up to {}x{})", display.width,
             display.height, max_render.width, max_render.height);
    return true;
}
