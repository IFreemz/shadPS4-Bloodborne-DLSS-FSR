void SetFrame(const FrameGen::FrameInputs* inputs, const FrameGen::OverlayInputs* overlays,
              vk::CommandBuffer command, vk::Extent2D backbuffer, vk::Rect2D game_area) {
    if (!active || !current_swapchain)
        return;
    const auto now = std::chrono::steady_clock::now();
    const float frame_ms = last_frame.time_since_epoch().count()
                               ? std::chrono::duration<float, std::milli>(now - last_frame).count()
                               : 16.7f;
    last_frame = now;
    if (inputs && !EnsureContext(backbuffer, inputs->render, inputs->depth_inverted))
        inputs = nullptr;
    if (!context)
        return;

    ++frame_id;
    ffxConfigureDescFrameGeneration config{};
    config.header.type = FFX_API_CONFIGURE_DESC_TYPE_FRAMEGENERATION;
    config.swapChain = current_swapchain;
    config.frameGenerationCallback = DispatchGeneration;
    config.frameGenerationCallbackUserContext = &context;
    config.frameGenerationEnabled = inputs != nullptr;
    config.allowAsyncWorkloads = false;
    if (inputs && overlays)
        config.HUDLessColor = Image(overlays->hudless, overlays->hudless_format, overlays->extent,
                                    FFX_API_RESOURCE_STATE_PIXEL_COMPUTE_READ);
    config.generationRect = {game_area.offset.x, game_area.offset.y, int(game_area.extent.width),
                             int(game_area.extent.height)};
    config.frameID = frame_id;
    if (inputs || configured_on) {
        const auto result = api.configure(&context, &config.header);
        if (result != FFX_API_RETURN_OK)
            LOG_WARNING(Render_Vulkan, "[FSR-FG] Configure failed ({})", result);
        if (bool(inputs) != configured_on)
            LOG_INFO(Render_Vulkan, "[FSR-FG] {}", inputs ? "On" : "Off");
        configured_on = inputs != nullptr;
    }
    if (!inputs)
        return;
    if (use_dlss)
        return StoreDlssInputs(command, *inputs, overlays);

    ffxDispatchDescFrameGenerationPrepareCameraInfo camera{};
    camera.header.type = FFX_API_DISPATCH_DESC_TYPE_FRAMEGENERATION_PREPARE_CAMERAINFO;
    std::copy_n(inputs->position.data(), 3, camera.cameraPosition);
    std::copy_n(inputs->up.data(), 3, camera.cameraUp);
    std::copy_n(inputs->right.data(), 3, camera.cameraRight);
    std::copy_n(inputs->forward.data(), 3, camera.cameraForward);
    ffxDispatchDescFrameGenerationPrepare prepare{};
    prepare.header.type = FFX_API_DISPATCH_DESC_TYPE_FRAMEGENERATION_PREPARE;
    prepare.header.pNext = &camera.header;
    prepare.frameID = frame_id;
    prepare.commandList = static_cast<VkCommandBuffer>(command);
    prepare.renderSize = {inputs->render.width, inputs->render.height};
    // Same conventions as the upscaler: jitter and motion in render pixels.
    prepare.jitterOffset = {inputs->jitter[0], inputs->jitter[1]};
    prepare.motionVectorScale = {1.0f, 1.0f};
    prepare.frameTimeDelta = frame_ms;
    prepare.cameraNear = inputs->near_plane;
    prepare.cameraFar = inputs->far_plane;
    prepare.cameraFovAngleVertical = inputs->fov_y;
    prepare.viewSpaceToMetersFactor = 1.0f;
    prepare.depth = Image(inputs->depth, vk::Format::eR32Sfloat, inputs->render,
                          FFX_API_RESOURCE_STATE_PIXEL_COMPUTE_READ);
    prepare.motionVectors = Image(inputs->motion, vk::Format::eR16G16Sfloat, inputs->render,
                                  FFX_API_RESOURCE_STATE_PIXEL_COMPUTE_READ);
    const auto result = api.dispatch(&context, &prepare.header);
    if (result != FFX_API_RETURN_OK)
        LOG_WARNING(Render_Vulkan, "[FSR-FG] Prepare failed ({})", result);
}

u32 TakeShown() {
    if (!active || !current_swapchain || !functions.pOutGetLastPresentCountFFXAPI)
        return 1;
    const u64 count = functions.pOutGetLastPresentCountFFXAPI(current_swapchain);
    const u64 shown = count - last_present_count;
    last_present_count = count;
    return u32(std::min<u64>(shown, 8));
}

